async def kb_for(db: AsyncSession) -> KnowledgeBase:
    return await KnowledgeBase.from_db(db)


async def kg_for(db: AsyncSession):
    return get_kg(await kb_for(db))


async def generate(db: AsyncSession, intent: dict, as_of: Optional[date], meta: dict, overrides: Optional[dict]) -> dict:
    kb = await kb_for(db)
    return synthesize(intent, kb, as_of or date.today(), meta, overrides)


async def save_generated(db: AsyncSession, gen: dict, intent: dict, actor: str = "buyer") -> Tender:
    m = gen["meta"]
    t = await tender_service.create_tender(db, m["title"], m["reference_no"], m["organisation"], status="draft",
                                           as_of=date.fromisoformat(m["publication"]))
    await tender_service.add_document(db, t, "generated_tender.txt", gen["text"].encode("utf-8"), "tender")
    t = await db.get(Tender, t.id)
    t.generation = {"intent": intent, "sections": gen["sections"], "verification": gen["verification"], "lines": gen["lines"],
                    "competition_guard": gen["competition_guard"], "watchlist": gen["watchlist"], "basis_counts": gen["basis_counts"],
                    "standards_register": gen["standards_register"], "regulations_register": gen["regulations_register"],
                    "route_advice": gen["route_advice"], "meta": m, "generator": gen["generator"], "kg_snapshot": gen["kg_snapshot"], "as_of": gen["as_of"]}
    flag_modified(t, "generation")
    await db.commit()
    await tender_service.compile_tender(db, t.id, actor=actor, reason="generated by Tender Studio")
    await ledger_service.append(db, actor, "tender.generated", "tender", t.id, {
        "input": (intent.get("input") or "")[:300], "generator": gen["generator"], "kg_snapshot": gen["kg_snapshot"],
        "passes": [{"pass": p["pass"], "readiness": p["readiness"], "gate": p["gate"]} for p in gen["verification"]["passes"]],
        "competition_guard": gen["competition_guard"]})
    return await db.get(Tender, t.id)


# ------------------------------------------------------------------------------------------ bid form
async def form_for(db: AsyncSession, tender_id: str) -> Tuple[Tender, dict]:
    t = await db.get(Tender, tender_id)
    if t is None:
        raise ValueError("tender not found")
    twin = t.twin or await tender_service.compile_tender(db, tender_id, reason="bid form")
    form = bidform.derive_form(twin)
    form["tender"]["id"] = t.id
    form["tender"]["status"] = t.status
    form["tender"]["organisation"] = t.organisation
    return t, form


def evidence_from_files(files: List[Tuple[str, bytes]]) -> Tuple[List[dict], List[dict], List[dict]]:
    docs, parsed_meta, security = [], [], []
    for name, data in files:
        parsed = parse_document(data, name)
        ev = extract_evidence(parsed)
        docs.append(ev)
        m = parsed.meta()
        parsed_meta.append({"filename": name, "sha256": parsed.sha256, "parser": parsed.parser, "pages": parsed.page_count,
                            "ocr": m.get("ocr"), "warnings": parsed.warnings, "doc_type": ev["meta"]["doc_type"],
                            "domains": ev["meta"].get("domains"), "facts": len(ev["items"])})
        hits = scan_injection(parsed.text)
        if hits:
            security.append({"file": name, "hits": hits[:3]})
        docs[-1]["_raw"] = (name, data, parsed.text, parsed.sha256)
    return docs, parsed_meta, security


async def submit_bid(db: AsyncSession, tender_id: str, bidder: str, product_name: Optional[str], answers: Dict[str, dict],
                     scope: Optional[List[str]], files: List[Tuple[str, bytes]], financial: Optional[dict] = None,
                     declarations: Optional[dict] = None) -> Bid:
    t, form = await form_for(db, tender_id)
    docs, parsed_meta, security = evidence_from_files(files)
    auto = bidform.autofill(form, docs)
    merged = {**auto}
    for k, v in (answers or {}).items():
        merged[k] = {**(auto.get(k) or {}), **v}
    scope = scope or bidform.infer_scope(form, docs)
    sc = bidform.score(form, merged, scope=scope)
    decl = bidform.declared_evidence_doc(form, merged, bidder)
    ev_docs = [{k: v for k, v in d.items() if k != "_raw"} for d in docs]
    mres = mirror(t.twin, ev_docs + ([decl] if decl["items"] or decl["meta"].get("licence_no") else []), bidder=bidder, scope_domains=scope)
    mres["product_name"] = product_name
    mres["security_flags"] = security
    bid = Bid(tender_id=tender_id, bidder=bidder, product_name=product_name, result=mres, evidence=ev_docs,
              compliance_score=mres["compliance_score"], verdict=mres["verdict"],
              form={"answers": merged, "score": sc, "scope": scope, "files": parsed_meta, "form_hash": form.get("content_hash"),
                    "declarations": declarations or {}},
              match_index=sc["match_index"])
    db.add(bid)
    await db.flush()
    commitment = None
    if financial:
        import secrets
        from app.engine.evaluation import commitment as commit_fn
        salt = secrets.token_hex(8)
        commitment = commit_fn(bid.id, financial, salt)
        bid.form = {**bid.form, "financial": financial, "salt": salt, "commitment": commitment}
    for d in docs:
        name, data, text, sha = d["_raw"]
        db.add(BidDocument(bid_id=bid.id, filename=name, doc_type=d["meta"]["doc_type"], sha256=sha, content=data, text=text))
    await db.commit()
    await db.refresh(bid)
    await ledger_service.append(db, bidder, "bid.submitted", "bid", bid.id, {
        "tender_id": tender_id, "match_index": sc["match_index"], "tier": sc["tier"], "knockouts": sc["knockouts"],
        "files": [{"f": m["filename"], "sha256": m["sha256"]} for m in parsed_meta], "answers_hash": _h(merged),
        "financial_commitment": commitment, "declarations": declarations or {},
        "tender_content_hash": (t.twin.get("provenance") or {}).get("content_hash")})
    return bid


def _h(obj) -> str:
    import hashlib
    return hashlib.sha256(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()


async def comparative(db: AsyncSession, tender_id: str) -> dict:
    t, form = await form_for(db, tender_id)
    bids = (await db.execute(select(Bid).where(Bid.tender_id == tender_id).order_by(Bid.created_at))).scalars().all()
    cols = []
    for b in bids:
        if b.form and b.form.get("score"):
            sc = b.form["score"]
        else:
            # legacy document-only bid (Bid Mirror): score it through the form using its stored evidence
            docs = b.evidence or []
            ans = bidform.autofill(form, docs)
            sc = bidform.score(form, ans, scope=bidform.infer_scope(form, docs))
        cols.append({"bid_id": b.id, "bidder": b.bidder, "product_name": b.product_name, "match_index": sc["match_index"], "tier": sc["tier"],
                     "knockouts": sc["knockouts"], "scope": sc.get("scope"), "by_field": {r["field_id"]: r for r in sc["results"]}})
    rows = []
    for f in form["fields"]:
        cells = []
        for c in cols:
            r = c["by_field"].get(f["id"])
            cells.append({"bid_id": c["bid_id"], "status": r["status"] if r else "N/A", "detail": r["detail"] if r else "not quoted",
                          "evidence": r["evidence_label"] if r else None} if r or True else None)
        rows.append({"field_id": f["id"], "group": f["group"], "label": f["label"], "clause_key": f.get("clause_key"),
                     "requirement": f.get("requirement"), "type": f["type"], "cells": cells})
    ranking = sorted([{k: c[k] for k in ("bid_id", "bidder", "product_name", "match_index", "tier", "knockouts", "scope")} for c in cols],
                     key=lambda c: (c["knockouts"] > 0, -c["match_index"]))
    responsive = [c for c in ranking if c["knockouts"] == 0]
    notes = []
    if len(responsive) == 1:
        notes.append("Only one technically responsive bid — single-bid situation; review competition before award (GFR Rule 173).")
    if not responsive and cols:
        notes.append("No bid is technically responsive — consider re-tendering after reviewing restrictive clauses.")
    return {"tender": form["tender"], "groups": form["groups"], "rows": rows, "bidders": ranking, "notes": notes,
            "disclaimer": "Comparative statement of technical bids generated for the Tender Evaluation Committee. Statuses are deterministic "
                          "comparisons against the clauses; award decisions rest with the committee."}
