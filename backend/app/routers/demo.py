"""One-click demo: seed a realistic (fictional) tender, corrigenda and a bidder evidence set."""
import os

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import FileResponse
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import get_db
from app.models import Bid, Tender, TenderDocument
from app.services import bid_service, tender_service

router = APIRouter()
DEMO_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "data", "demo"))
DEMO_REF = "DEMO/PWD/2026/0412"
LED_REF = "DEMO/MC/ELE/2026/077"
BIDDER_FILES = ["datasheet_arya_tmt.txt", "licence_arya_tmt.txt", "test_report_arya_tmt.txt"]
STUDIO_REQUEST = "6000 LED bulbs 9 watt B22 and 2000 metres 1.5 sq mm FR copper wire for District Hospital Demo City within 30 days"
STUDIO_TITLE = "Supply of LED lamps and wiring cable for District Hospital, Demo City (DEMO — generated by Tender Studio)"
# (bidder, product, evidence files, sealed price per lamp, declarations)
LED_BIDS = [
    ("Gyan Jyoti Electricals (fictional)", "GJ-LED-9B", ["led/registration_jyoti_led.txt", "led/datasheet_jyoti_led.txt", "led/test_report_scan_jyoti_led.png"],
     72.0, {"mse": False, "mii_class": "II", "local_content": 38}),
    ("Harit Lighting Udyog (fictional)", "HL-9 Pro", ["led/registration_harit_led.txt", "led/datasheet_harit_led.txt", "led/test_report_harit_led.txt"],
     79.0, {"mse": True, "mii_class": "I", "local_content": 64}),
    ("Chandni Lamps (fictional)", "CL-9 Economy", ["led/registration_chandni_led.txt", "led/datasheet_chandni_led.txt"],
     58.0, {"mse": False, "mii_class": "non-local", "local_content": 12}),
]


def _read(name: str) -> bytes:
    with open(os.path.join(DEMO_DIR, name), "rb") as f:
        return f.read()


async def seed_demo(db: AsyncSession) -> dict:
    out = {}
    t = (await db.execute(select(Tender).where(Tender.reference_no == DEMO_REF))).scalars().first()
    if t is None:
        t = await tender_service.create_tender(db, "Supply of Cement & TMT Steel — G+3 Primary Health Centre (DEMO)", DEMO_REF,
                                               "Public Works Department, Demo Division (fictional)")
        await tender_service.add_document(db, t, "tender_phc_building.txt", _read("tender_phc_building.txt"), "tender")
        await tender_service.compile_tender(db, t.id, actor="demo", reason="demo seed")
    out["tender_id"] = t.id
    led = (await db.execute(select(Tender).where(Tender.reference_no == LED_REF))).scalars().first()
    if led is None:
        led = await tender_service.create_tender(db, "Supply of LED Street Light Luminaires — Ward 12 (DEMO)", LED_REF,
                                                 "Municipal Corporation of Demo City (fictional)", status="published")
        await tender_service.add_document(db, led, "tender_led_streetlight.txt", _read("tender_led_streetlight.txt"), "tender")
        await tender_service.compile_tender(db, led.id, actor="demo", reason="demo seed")
    out["led_tender_id"] = led.id
    bid = (await db.execute(select(Bid).where(Bid.tender_id == t.id))).scalars().first()
    if bid is None:
        bid = await bid_service.create_bid(db, t.id, "Arya Rebar Ltd (fictional)", "Arya TMT Fe 500D",
                                           [(n, _read(os.path.join("bidder", n))) for n in BIDDER_FILES])
    out["bid_id"] = bid.id
    # Tender Studio: one sentence -> verified, published tender -> contractors bid through the smart form
    gen_t = (await db.execute(select(Tender).where(Tender.title == STUDIO_TITLE))).scalars().first()
    if gen_t is not None and ((gen_t.generation or {}).get("intent") or {}).get("input") != STUDIO_REQUEST:
        gen_t.title, gen_t.status = STUDIO_TITLE + " — superseded demo", "archived"   # older seed (different quantities)
        await db.commit()
        gen_t = None
    if gen_t is None:
        from datetime import date
        from app.engine.intent import apply_answers, parse
        from app.services import studio_service
        intent = parse(STUDIO_REQUEST)
        gen = await studio_service.generate(db, intent, date(2026, 9, 25), {"organisation": "District Health Society, Demo City (fictional)",
                                                                             "title": STUDIO_TITLE}, None)
        gen_t = await studio_service.save_generated(db, gen, intent, actor="demo")
        if gen_t.gate != "BLOCKED":
            gen_t.status = "published"
            await db.commit()
        _, form = await studio_service.form_for(db, gen_t.id)
        accept = {f["id"]: {"accepted": True} for f in form["fields"] if f["type"] == "declaration"}
        for f in form["fields"]:
            if f["type"] == "number" and f.get("commercial") and f["group"] in ("lighting", "general"):
                accept[f["id"]] = {"value": (f["norm"].get("min") or f["norm"].get("max"))}
        led_line = next((l["index"] for l in (gen_t.generation or {}).get("lines", []) if l["item_id"] == "led_lamp"), 1)
        for bidder, product, files, price, decl in LED_BIDS:
            await studio_service.submit_bid(db, gen_t.id, bidder, product, accept, ["lighting"],
                                            [(os.path.basename(f), _read(os.path.join("bidder", f))) for f in files],
                                            financial={"lines": {str(led_line): {"unit_price": price}}}, declarations=decl)
    out["studio_tender_id"] = gen_t.id
    return out


@router.post("/demo/seed", summary="Seed the demo tender, a second (clean) tender and a demo bid")
async def seed(db: AsyncSession = Depends(get_db)):
    return await seed_demo(db)


@router.get("/demo", summary="Demo ids")
async def demo_ids(db: AsyncSession = Depends(get_db)):
    t = (await db.execute(select(Tender).where(Tender.reference_no == DEMO_REF))).scalars().first()
    led = (await db.execute(select(Tender).where(Tender.reference_no == LED_REF))).scalars().first()
    bid = (await db.execute(select(Bid).where(Bid.tender_id == t.id))).scalars().first() if t else None
    applied = []
    if t:
        applied = [d.filename for d in (await db.execute(select(TenderDocument).where(TenderDocument.tender_id == t.id, TenderDocument.doc_type == "corrigendum"))).scalars().all()]
    gen_t = (await db.execute(select(Tender).where(Tender.title == STUDIO_TITLE))).scalars().first()
    return {"tender_id": t.id if t else None, "led_tender_id": led.id if led else None, "bid_id": bid.id if bid else None,
            "studio_tender_id": gen_t.id if gen_t else None, "studio_request": STUDIO_REQUEST,
            "corrigenda_applied": applied, "files": sorted(x for x in os.listdir(DEMO_DIR) if os.path.isfile(os.path.join(DEMO_DIR, x))) + [f"bidder/{f}" for f in BIDDER_FILES]
                     + [f"bidder/{f}" for _, _, fs, _, _ in LED_BIDS for f in fs]}


@router.post("/demo/tenders/{tender_id}/corrigendum/{n}", summary="Apply demo corrigendum 1 or 2 (shows fix + regression detection)")
async def apply_corrigendum(tender_id: str, n: int, db: AsyncSession = Depends(get_db)):
    if n not in (1, 2):
        raise HTTPException(400, "n must be 1 or 2")
    t = await db.get(Tender, tender_id)
    if t is None:
        raise HTTPException(404, "Tender not found")
    name = f"corrigendum_{n}.txt"
    exists = (await db.execute(select(TenderDocument).where(TenderDocument.tender_id == tender_id, TenderDocument.filename == name))).scalars().first()
    if not exists:
        await tender_service.add_document(db, t, name, _read(name), "corrigendum")
    twin = await tender_service.compile_tender(db, tender_id, actor="demo", reason=f"corrigendum {n}")
    return {"readiness": twin["readiness"], "delta": twin.get("delta"), "changelog": twin["corrigenda"]["changelog"]}


@router.get("/demo/files/{path:path}", summary="Download a demo sample document")
async def demo_file(path: str):
    full = os.path.abspath(os.path.join(DEMO_DIR, path))
    if not full.startswith(DEMO_DIR) or not os.path.isfile(full):
        raise HTTPException(404, "not found")
    return FileResponse(full, filename=os.path.basename(full))
